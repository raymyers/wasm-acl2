// Make deck.h from a deck in sent's format: DECK[] holds the bytes of the
// file and DECK_LEN its length. Usage: node gen-deck.mjs DECK.txt > deck.h
import { readFileSync } from 'node:fs';
const file = process.argv[2], data = readFileSync(file);
const out = [`/* Generated by gen-deck.mjs from ${file.split('/').pop()} */`,
  `#define DECK_LEN ${data.length}u`, `static const unsigned char DECK[${Math.max(data.length, 1)}] = {`];
for (let i = 0; i < data.length; i += 16) out.push('  ' + [...data.subarray(i, i + 16)].join(',') + ',');
out.push('};');
console.log(out.join('\n'));
