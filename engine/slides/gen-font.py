# Make font.h, the 6x12 glyphs of printable ASCII (32..126), from Spleen's
# BDF file (nixpkgs#spleen, share/fonts/misc/spleen-6x12.bdf).
# Usage: python3 -I gen-font.py spleen-6x12.bdf > font.h
import sys
bdf = open(sys.argv[1]).read().split('\n')
glyphs, enc, rows, inbmp = {}, None, [], False
for line in bdf:
    if line.startswith('ENCODING '): enc = int(line.split()[1]); rows = []
    elif line == 'BITMAP': inbmp = True
    elif line == 'ENDCHAR':
        inbmp = False
        if enc is not None and 32 <= enc <= 126: glyphs[enc] = rows
    elif inbmp: rows.append(int(line, 16))
assert all(len(glyphs.get(c, [])) == 12 for c in range(32, 127)), 'missing glyph'
