// T5 oracle: invoke every exported function of the binary corpus
// (../sem/wasm/*.wasm, see gen-wasm-corpus.mjs) on a few deterministic
// argument sets under V8, and write ../sem/invoke-vectors.lsp:
//   (FILE EXPORT (PARAM-TYPE...) (ARG-BITS...) RESULT)
// RESULT is a list of result bit patterns, :TRAP, or :NAN (any NaN).
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "../sem/wasm");

const VALS = {
  i32: [0n, 1n, 7n, 12n, 100n, 0xffffffffn, 0x80000000n, 3n],
  i64: [0n, 1n, 7n, 12n, 100n, 0xffffffffffffffffn, 0x8000000000000000n, 3n],
  f32: [0x00000000n, 0x3fc00000n, 0xc0100000n, 0x7fc00000n, 0x7f800000n, 0x80000000n, 0x41200000n, 0x3f800000n],
  f64: [0n, 0x3ff8000000000000n, 0xc002000000000000n, 0x7ff8000000000000n, 0x7ff0000000000000n,
        0x8000000000000000n, 0x4024000000000000n, 0x3ff0000000000000n],
};
// Loop programs whose running time depends on an argument get explicit
// argument sets: the generic ones above would ask for ~2^16 iterations over a
// 64 KiB memory (e.g. djb2(0, 2^32-1) traps only at the end of memory), which
// exceeds the generated STEPS fuel (10^6 steps). These still cover the
// out-of-bounds trap at the memory edge.
const ARGS = {
  "hash.wasm djb2": [[0n, 2n], [0n, 0n], [1n, 1n], [0n, 40n], [65532n, 1n], [65533n, 1n], [65530n, 10n]],
  "sum_array.wasm sum_array": [[0n, 5n], [0n, 0n], [4n, 3n], [8n, 40n], [65532n, 1n], [65533n, 1n], [65520n, 10n]],
  "is_prime.wasm is_prime": [[0n], [1n], [2n], [7n], [97n], [100n], [7919n], [65521n], [4294967295n]],
};
const f32 = new Float32Array(1), u32 = new Uint32Array(f32.buffer);
const f64 = new Float64Array(1), u64 = new BigUint64Array(f64.buffer);
function toJS(t, b) {
  if (t === "i32") return Number(BigInt.asIntN(32, b));
  if (t === "i64") return BigInt.asIntN(64, b);
  if (t === "f32") { u32[0] = Number(b); return f32[0]; }
  u64[0] = b; return f64[0];
}
function fromJS(t, v) {
  if (t === "i32") return BigInt(v >>> 0);
  if (t === "i64") return BigInt.asUintN(64, v);
  if (t === "f32") { f32[0] = v; return Number.isNaN(v) ? ":NAN" : BigInt(u32[0]); }
  f64[0] = v; return Number.isNaN(v) ? ":NAN" : u64[0];
}

const out = ["; GENERATED by tests/oracle/gen-invoke-vectors.mjs (V8 " + process.version + "). Do not edit.",
             "; (FILE EXPORT (PARAM-TYPES) (ARG-BITS) (RESULT-BITS) | :TRAP | :NAN)", "("];
for (const f of readdirSync(dir).filter((f) => f.endsWith(".wasm")).sort()) {
  const dump = execFileSync("wasm-objdump", ["-x", join(dir, f)]).toString();
  const types = [...dump.matchAll(/type\[(\d+)\] \(([^)]*)\) -> (\S+)/g)].map((m) => ({
    params: m[2].split(",").map((s) => s.trim()).filter(Boolean),
    result: m[3] === "nil" ? [] : [m[3]],
  }));
  const sig = {};
  for (const m of dump.matchAll(/ - func\[(\d+)\] sig=(\d+)/g)) sig[m[1]] = types[Number(m[2])];
  const { instance } = await WebAssembly.instantiate(readFileSync(join(dir, f)));
  for (const m of dump.matchAll(/ - func\[(\d+)\] <[^>]*> -> "([^"]+)"/g)) {
    const s = sig[m[1]];
    if (!s || s.params.some((p) => !VALS[p])) continue;
    const sets = ARGS[`${f} ${m[2]}`] ??
      [0, 1, 2, 3].map((i) => s.params.map((p, j) => VALS[p][(i * 3 + j * 5) % VALS[p].length]));
    for (const args of sets) {
      let res;
      try {
        const r = instance.exports[m[2]](...args.map((a, j) => toJS(s.params[j], a)));
        if (s.result.length === 0) res = "()";
        else { const v = fromJS(s.result[0], r); res = v === ":NAN" ? ":NAN" : `(${v})`; }
      } catch (e) { res = ":TRAP"; }
      out.push(` ("${f}" "${m[2]}" (${s.params.map((p) => ":" + p.toUpperCase()).join(" ")}) (${args.join(" ")}) ${res})`);
    }
  }
}
out.push(")");
writeFileSync(join(here, "../sem/invoke-vectors.lsp"), out.join("\n") + "\n");
