// Instruction typing cases for the generated 3.0 semantics (wasm3 M6), with
// V8 as the oracle: each case is a function body in WAT, wrapped in a module
// (a callee $f : [(ref null i31)] -> [], a callee $g : [i64] -> [], a tag
// $e : [] -> []), and V8's WebAssembly.validate says whether it is valid.
//
//   WASM_REF=$(nix build ..#wasm-ref-interp --print-out-paths)/bin/wasm \
//     node gen-typing-oracle.mjs > ../sem-3.0/typing-oracle-3.0.lsp
//
// The WAT is turned into binary by the reference interpreter (wabt's text
// parser lacks the GC heap types), unchecked (-u), so V8 alone decides.
//
// Output: ((NAME . T|NIL|:NO-WAT) ...); :NO-WAT when the interpreter cannot build
// the module (then the test book uses the expected answer it states). The
// test book tests/sem-3.0/t6-instr-typing-3.0.lisp has the same names with
// the instructions in the generated encoding.
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

// [name, params, results, locals, body]
const cases = [
  ["const add : i32", "", "i32", "", "i32.const 1 i32.const 2 i32.add"],
  ["add without operands", "", "i32", "", "i32.add"],
  ["empty : []", "", "", "", ""],
  ["empty : i32", "", "i32", "", ""],
  ["const drop : []", "", "", "", "i32.const 1 drop"],
  ["two results left", "", "i32", "", "i32.const 1 i32.const 2"],
  ["frame: param kept below", "i32", "i32", "", "local.get 0 i32.const 1 drop"],
  ["subsumption at block end", "", "(ref null i31)", "", "block (result (ref null i31)) i32.const 1 ref.i31 end"],
  ["subsumption at function end", "", "anyref", "", "i32.const 1 ref.i31"],
  ["no subsumption downward", "", "(ref i31)", "", "ref.null i31"],
  ["subsumption at a call", "", "", "", "i32.const 1 ref.i31 call $f"],
  ["call with a wrong operand", "", "", "", "i32.const 1 call $g"],
  ["uninitialized non-defaultable local", "", "", "(ref i31)", "local.get 0 drop"],
  ["initialized non-defaultable local", "", "", "(ref i31)", "i32.const 1 ref.i31 local.set 0 local.get 0 drop"],
  ["dead code after unreachable", "", "i32", "", "unreachable i32.add"],
  ["dead code after br", "", "", "", "block br 0 i32.add drop end"],
  ["dead code after throw", "", "i32", "", "throw $e i32.add"],
  ["dead code with a wrong type", "", "i32", "", "unreachable i64.const 0 i32.add"],
  ["br with a value", "", "i32", "", "block (result i32) i32.const 1 br 0 end"],
  ["br_if", "", "i32", "", "block (result i32) i32.const 1 i32.const 0 br_if 0 end"],
  ["select", "", "i32", "", "i32.const 1 i32.const 2 i32.const 0 select"],
  ["return", "", "i32", "", "i32.const 1 return"],
  ["return with a wrong type", "", "i32", "", "i64.const 1 return"],
  ["nested blocks", "", "i32", "", "block (result i32) block (result i32) i32.const 7 end end"],
];

const dir = mkdtempSync(join(tmpdir(), "w3t-typing-"));
const sig = (kw, ts) => (ts ? `(${kw} ${ts})` : "");
const out = ["; GENERATED by tests/oracle/gen-typing-oracle.mjs (Node " + process.version + ", V8 WebAssembly.validate). Do not edit.", "("];
for (const [name, params, results, locals, body] of cases) {
  const wat = `(module
  (type $t (func (param (ref null i31))))
  (func $f (type $t))
  (func $g (param i64))
  (tag $e)
  (func ${sig("param", params)} ${sig("result", results)} ${sig("local", locals)} ${body}))`;
  writeFileSync(join(dir, "m.wat"), wat);
  let verdict;
  try {
    execFileSync(process.env.WASM_REF, ["-u", "-d", join(dir, "m.wat"), "-o", join(dir, "m.wasm")], { stdio: "pipe" });
    verdict = WebAssembly.validate(readFileSync(join(dir, "m.wasm"))) ? "T" : "NIL";
  } catch (e) {
    verdict = ":NO-WAT";
  }
  out.push(` ("${name}" . ${verdict})`);
}
out.push(")");
console.log(out.join("\n"));
