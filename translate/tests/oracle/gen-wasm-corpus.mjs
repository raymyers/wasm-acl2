// Build the binary test corpus for the generated parser (GRAM/BMODULE):
// every ../../../tests/oracle/*.wat (the corpus shared with WASM1) is
// compiled with wat2wasm into ../sem/wasm/NAME.wasm, and V8's view of each
// module (export names + kinds) is written to ../sem/wasm-corpus.lsp.
//
//   node gen-wasm-corpus.mjs
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "../../../tests/oracle");
const out = join(here, "../sem/wasm");
mkdirSync(out, { recursive: true });

const lines = [
  "; GENERATED by tests/oracle/gen-wasm-corpus.mjs from tests/oracle/*.wat (wat2wasm + V8).",
  "; (FILE (EXPORT-NAME KIND) ...) as reported by WebAssembly.Module.exports. Do not edit.",
  "(",
];
for (const f of readdirSync(src).filter((f) => f.endsWith(".wat")).sort()) {
  const name = basename(f, ".wat");
  const wasm = join(out, name + ".wasm");
  execFileSync("wat2wasm", [join(src, f), "-o", wasm]);
  const mod = new WebAssembly.Module(readFileSync(wasm));
  const exps = WebAssembly.Module.exports(mod).map((e) => `("${e.name}" :${e.kind.toUpperCase()})`);
  lines.push(` ("${name}.wasm" ${exps.join(" ")})`);
}
lines.push(")");
writeFileSync(join(here, "../sem/wasm-corpus.lsp"), lines.join("\n") + "\n");
