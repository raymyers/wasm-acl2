// SIMD test vectors for the generated WASM 2.0 semantics (wasm3 prep P4, 2.0
// gate), with Node/V8 as the oracle.
//
//   node gen-simd-vectors.mjs > ../sem-2.0/simd-vectors-2.0.lsp
//
// Each vector is (OP A B [C] RESULT): v128 values as naturals (lane 0 in the
// low bits). Float operands are finite and moderate, so no result lane is a
// NaN and results compare exactly. Deterministic: fixed PRNG seed. The ops
// cover the builtins 2.0 adds for SIMD: lanes_/inv_lanes_ (every op),
// iavgr_, iq15mulr_sat_, narrow__, ibitselect_, iandnot_, fpmin_/fpmax_.
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

// [wat op, arity (v128 operands), float lane width or 0]
const ops = [
  ["i8x16.add", 2, 0], ["i16x8.sub", 2, 0], ["i32x4.mul", 2, 0], ["i64x2.add", 2, 0],
  ["i8x16.add_sat_s", 2, 0], ["i16x8.sub_sat_u", 2, 0],
  ["i8x16.avgr_u", 2, 0], ["i16x8.avgr_u", 2, 0],
  ["i16x8.q15mulr_sat_s", 2, 0],
  ["i8x16.min_s", 2, 0], ["i32x4.max_u", 2, 0],
  ["i8x16.narrow_i16x8_s", 2, 0], ["i16x8.narrow_i32x4_u", 2, 0],
  ["v128.and", 2, 0], ["v128.andnot", 2, 0], ["v128.bitselect", 3, 0],
  ["f32x4.add", 2, 32], ["f64x2.mul", 2, 64], ["f32x4.min", 2, 32], ["f64x2.max", 2, 64],
  ["f32x4.pmin", 2, 32], ["f64x2.pmax", 2, 64],
];

const v = (i) => `(i64x2.replace_lane 1 (i64x2.splat (local.get ${2 * i})) (local.get ${2 * i + 1}))`;
const wat = "(module\n" + ops.map(([name, k]) => {
  const params = Array(2 * k).fill("i64").join(" ");
  const args = Array.from({ length: k }, (_, i) => v(i)).join(" ");
  return `  (func (export "${name}") (param ${params}) (result i64 i64) (local $r v128)
    (local.set $r (${name} ${args}))
    (i64x2.extract_lane 0 (local.get $r)) (i64x2.extract_lane 1 (local.get $r)))`;
}).join("\n") + ")\n";

const dir = mkdtempSync(join(tmpdir(), "w2t-simd-"));
writeFileSync(join(dir, "simd.wat"), wat);
execFileSync("wat2wasm", [join(dir, "simd.wat"), "-o", join(dir, "simd.wasm")]);
const { instance } = await WebAssembly.instantiate(readFileSync(join(dir, "simd.wasm")));
const ex = instance.exports;

let st = 0x9E3779B97F4A7C15n;
const M64 = (1n << 64n) - 1n;
function rnd64() { st ^= st >> 12n; st ^= (st << 25n) & M64; st ^= st >> 27n; return (st * 0x2545F4914F6CDD1Dn) & M64; }
// a 64-bit half of an operand: random bits, or moderate float lanes
function half(fw) {
  const r = rnd64();
  if (fw === 32) {
    const lane = (x) => (x & 0x803fffffn) | ((((x >> 24n) & 0xffn) % 40n + 107n) << 23n);
    return lane(r & 0xffffffffn) | (lane(r >> 32n) << 32n);
  }
  if (fw === 64) return (r & 0x800fffffffffffffn) | ((((r >> 52n) & 0x7ffn) % 80n + 983n) << 52n);
  return (r & 3n) === 0n ? (r & 0x00ff00ff00ff00ffn) : r;   // some lanes small
}
const s64 = (x) => BigInt.asIntN(64, x);
const u64 = (x) => BigInt.asUintN(64, BigInt(x));

const out = [];
out.push("; GENERATED by tests/oracle/gen-simd-vectors.mjs (Node " + process.version + " as oracle).");
out.push("; (OP A B [C] RESULT): v128 values as naturals, lane 0 in the low bits. Do not edit.");
out.push("(");
for (const [name, k, fw] of ops) {
  for (let i = 0; i < 24; i++) {
    const halves = Array.from({ length: 2 * k }, () => half(fw));
    const [lo, hi] = ex[name](...halves.map(s64));
    const vals = Array.from({ length: k }, (_, j) => halves[2 * j] | (halves[2 * j + 1] << 64n));
    out.push(` ("${name}" ${vals.join(" ")} ${u64(lo) | (u64(hi) << 64n)})`);
  }
}
out.push(")");
console.log(out.join("\n"));
